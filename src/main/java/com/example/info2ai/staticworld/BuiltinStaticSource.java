package com.example.info2ai.staticworld;

import com.example.info2ai.events.EventData;
import com.example.info2ai.model.Facts;
import com.example.info2ai.model.StaticWorldInfo;
import com.example.info2ai.model.StructureInfo;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.PriorityQueue;
import java.util.concurrent.TimeUnit;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.structure.StructureSet;
import net.minecraft.util.math.BlockPos;
import net.minecraft.util.math.ChunkPos;
import net.minecraft.util.math.random.CheckedRandom;
import net.minecraft.util.math.random.ChunkRandom;
import net.minecraft.world.HeightLimitView;
import net.minecraft.world.biome.source.BiomeAccess;
import net.minecraft.world.gen.chunk.placement.ConcentricRingsStructurePlacement;
import net.minecraft.world.gen.chunk.placement.RandomSpreadStructurePlacement;
import net.minecraft.world.gen.structure.JigsawStructure;
import net.minecraft.world.gen.structure.Structure;

/** Computes static facts from the live generator's inputs on the static worker. */
public final class BuiltinStaticSource implements StaticWorldSource {
    private static final String BIOME_SCALE_NOTE = "position at recorded bucket sampling origin; not current-player biome";
    private static final String TERRAIN_NOTE = "computed from the game's own world generation; player edits and chunks generated by older versions are not modeled";
    private static final int RESULT_LIMIT = 32;
    private static final int CANDIDATE_LIMIT = 4096;
    private static final int INITIAL_RADIUS = 512;
    private static final long CHECK_ALLOWANCE_NANOS = TimeUnit.MILLISECONDS.toNanos(20);
    static final long BUDGET_NANOS = TimeUnit.MILLISECONDS.toNanos(200);
    private static final Comparator<Candidate> NEAREST = Comparator.comparingLong(Candidate::distanceSquared)
        .thenComparingInt(candidate -> candidate.chunk().x).thenComparingInt(candidate -> candidate.chunk().z)
        .thenComparingInt(Candidate::setOrder);

    private record Candidate(StructureSet set, int setOrder, ChunkPos chunk, long distanceSquared) { }
    private record SearchArea(int x, int z, int radius, long innerDistanceSquared, long deadline, int limit) { }
    private record Start(Structure structure, Structure.StructurePosition position) { }
    record SearchResult(List<StructureInfo> structures, Facts coverage) { }

    @Override public String describe() {
        return "builtin";
    }

    @Override public String availableConfidence() {
        return "high";
    }

    @Override public boolean isAvailable(StaticQuery query) {
        return query.supported();
    }

    @Override public StaticWorldInfo getStatic(StaticQuery query) {
        if (!isAvailable(query)) return null;
        long started = System.nanoTime();
        var handle = query.context();
        int x = query.sampleX(), y = query.y(), z = query.sampleZ(), radius = query.candidateRadius();
        var biome = biomeAt(handle, x, y, z);
        var result = structuresAround(handle, x, z, radius, started, started + BUDGET_NANOS);
        var sampledQuery = EventData.of("x", x, "y", y, "z", z, "radius", radius, "dim", query.shortDimension(),
            "max", RESULT_LIMIT);
        var coverage = result.coverage();
        if (biome.toJson().get("id").isJsonNull()) {
            var fields = coverage.toJson();
            fields.addProperty("biome_unregistered", true);
            coverage = Facts.fromJson(fields);
        }
        return new StaticWorldInfo(describe(), availableConfidence(), biome, BIOME_SCALE_NOTE, result.structures(), List.of(),
            sampledQuery, coverage, System.currentTimeMillis());
    }

    static Facts biomeAt(GenerationHandle handle, int x, int y, int z) {
        var sampler = handle.noise().getMultiNoiseSampler();
        var access = new BiomeAccess((biomeX, biomeY, biomeZ) -> handle.biomeSource().getBiome(biomeX, biomeY, biomeZ, sampler),
            BiomeAccess.hashSeed(handle.seed()));
        var biome = access.getBiome(new BlockPos(x, y, z));
        var id = biome.getKey().map(key -> key.getValue())
            .orElseGet(() -> handle.registries().get(RegistryKeys.BIOME).getId(biome.value()));
        return EventData.of("id", id == null ? null : id.toString(), "x", x, "y", y, "z", z, "mode", "position");
    }

    static SearchResult structuresAround(GenerationHandle handle, int x, int z, int radius, long budgetNanos) {
        long started = System.nanoTime();
        return structuresAround(handle, x, z, radius, started, started + budgetNanos);
    }

    private static SearchResult structuresAround(GenerationHandle handle, int x, int z, int radius,
            long started, long deadline) {
        if (!handle.structuresEnabled()) return result(List.of(), radius, started, false, 0, 0, true);

        var sets = new ArrayList<StructureSet>();
        int skipped = 0, locateMargin = 0;
        for (var entry : handle.placements().getStructureSets()) {
            var set = entry.value();
            if (set.placement() instanceof RandomSpreadStructurePlacement || set.placement() instanceof ConcentricRingsStructurePlacement) {
                sets.add(set);
                var offset = set.placement().getLocatePos(ChunkPos.ORIGIN);
                locateMargin = Math.max(locateMargin, (int) Math.ceil(Math.hypot(offset.getX(), offset.getZ())));
            } else {
                skipped++;
            }
        }
        var structures = new ArrayList<StructureInfo>();
        var heights = HeightLimitView.create(handle.bottomY(), handle.height());
        int checked = 0;
        long checkAllowance = CHECK_ALLOWANCE_NANOS;
        boolean timeLimited = false;
        int searchRadius = radius + locateMargin;
        int outerRadius = Math.min(INITIAL_RADIUS, searchRadius);
        long innerDistanceSquared = -1;
        while (!timeLimited && checked < CANDIDATE_LIMIT && !expired(deadline)) {
            var area = new SearchArea(x, z, outerRadius, innerDistanceSquared, deadline, CANDIDATE_LIMIT - checked);
            var candidates = collectCandidates(handle, sets, area);
            ChunkPos currentChunk = null;
            var generated = new HashSet<Structure>();
            for (var candidate : candidates) {
                long before = System.nanoTime();
                // Vanilla calls cannot be interrupted safely. Leave room for the next full validation.
                if (deadline - before < checkAllowance) {
                    timeLimited = true;
                    break;
                }
                checked++;
                if (!candidate.chunk().equals(currentChunk)) {
                    currentChunk = candidate.chunk();
                    generated.clear();
                }
                // Vanilla skips a set if a previous set already produced one of its structures in this chunk.
                if (!generated.isEmpty() && candidate.set().structures().stream().anyMatch(entry -> generated.contains(entry.structure().value()))) continue;
                var start = findStructure(handle, heights, candidate, deadline);
                if (start != null) {
                    generated.add(start.structure());
                    var locate = candidate.set().placement().getLocatePos(candidate.chunk());
                    if (distanceSquared(locate.getX(), locate.getZ(), x, z) <= (long) radius * radius) {
                        var row = structureInfo(handle, locate, start);
                        if (row != null) structures.add(row);
                    }
                }
                checkAllowance = Math.max(checkAllowance, System.nanoTime() - before);
            }
            if (outerRadius == searchRadius) break;
            innerDistanceSquared = (long) outerRadius * outerRadius;
            outerRadius = Math.min(searchRadius, outerRadius * 2);
        }
        structures.sort(Comparator.comparingLong(row -> distanceSquared(row.x(), row.z(), x, z)));
        return result(structures, radius, started, timeLimited || expired(deadline), checked, skipped, false);
    }

    private static List<Candidate> collectCandidates(GenerationHandle handle, List<StructureSet> sets, SearchArea area) {
        var nearest = new PriorityQueue<>(NEAREST.reversed());
        for (int i = 0; i < sets.size() && !expired(area.deadline()); i++) {
            var set = sets.get(i);
            if (set.placement() instanceof RandomSpreadStructurePlacement spread) {
                collectSpread(handle, set, i, spread, area, nearest);
            } else if (set.placement() instanceof ConcentricRingsStructurePlacement rings) {
                var positions = handle.placements().getPlacementPositions(rings);
                if (positions == null) continue;
                for (var chunk : positions) {
                    if (expired(area.deadline())) break;
                    retainCandidate(handle, nearest, set, i, chunk, area);
                }
            }
        }
        var sorted = new ArrayList<>(nearest);
        sorted.sort(NEAREST);
        return sorted;
    }

    private static void collectSpread(GenerationHandle handle, StructureSet set, int setOrder,
            RandomSpreadStructurePlacement spread, SearchArea area, PriorityQueue<Candidate> nearest) {
        int spacing = spread.getSpacing();
        int regionWidth = spacing * 16;
        int minX = Math.floorDiv(area.x() - area.radius(), regionWidth), maxX = Math.floorDiv(area.x() + area.radius(), regionWidth);
        int minZ = Math.floorDiv(area.z() - area.radius(), regionWidth), maxZ = Math.floorDiv(area.z() + area.radius(), regionWidth);
        long seed = handle.placements().getStructureSeed();
        for (int rx = minX; rx <= maxX; rx++) {
            for (int rz = minZ; rz <= maxZ; rz++) {
                if (expired(area.deadline())) return;
                retainCandidate(handle, nearest, set, setOrder, spread.getStartChunk(seed, rx * spacing, rz * spacing), area);
            }
        }
    }

    private static void retainCandidate(GenerationHandle handle, PriorityQueue<Candidate> nearest, StructureSet set,
            int setOrder, ChunkPos chunk, SearchArea area) {
        long distanceSquared = distanceSquared(chunk.getStartX(), chunk.getStartZ(), area.x(), area.z());
        if (distanceSquared <= area.innerDistanceSquared() || distanceSquared > (long) area.radius() * area.radius()) return;
        var candidate = new Candidate(set, setOrder, chunk, distanceSquared);
        boolean full = nearest.size() == area.limit();
        if (full && NEAREST.compare(candidate, nearest.element()) >= 0) return;
        // Frequency-rejected positions must not exhaust the limit before other structure sets can contribute.
        if (!set.placement().shouldGenerate(handle.placements(), chunk.x, chunk.z)) return;
        if (full) nearest.remove();
        nearest.add(candidate);
    }

    private static long distanceSquared(int x, int z, int centerX, int centerZ) {
        long dx = (long) x - centerX, dz = (long) z - centerZ;
        return dx * dx + dz * dz;
    }

    private static Start findStructure(GenerationHandle handle, HeightLimitView heights,
            Candidate candidate, long deadline) {
        var entries = candidate.set().structures();
        var chunk = candidate.chunk();
        long seed = handle.placements().getStructureSeed();
        if (entries.size() == 1) {
            var structure = entries.getFirst().structure().value();
            var start = findStart(handle, heights, candidate, seed, structure, deadline);
            return start == null ? null : new Start(structure, start);
        }

        var choices = new ArrayList<>(entries);
        var random = new ChunkRandom(new CheckedRandom(0));
        random.setCarverSeed(seed, chunk.x, chunk.z);
        int totalWeight = choices.stream().mapToInt(StructureSet.WeightedEntry::weight).sum();
        while (!choices.isEmpty() && !expired(deadline)) {
            int draw = random.nextInt(totalWeight), index = 0;
            while ((draw -= choices.get(index).weight()) >= 0) index++;
            var selected = choices.remove(index);
            totalWeight -= selected.weight();
            var structure = selected.structure().value();
            var start = findStart(handle, heights, candidate, seed, structure, deadline);
            if (start != null) return new Start(structure, start);
        }
        return null;
    }

    private static Structure.StructurePosition findStart(GenerationHandle handle, HeightLimitView heights,
            Candidate candidate, long seed, Structure structure, long deadline) {
        if (expired(deadline)) return null;
        var context = new Structure.Context(handle.registries(), handle.generator(), handle.biomeSource(), handle.noise(),
            handle.templates(), seed, candidate.chunk(), heights, structure.getValidBiomes()::contains);
        var valid = structure.getValidStructurePosition(context);
        if (valid.isEmpty()) return null;
        var start = valid.get();
        if (structure instanceof JigsawStructure && (expired(deadline) || start.generate().toList().pieces().isEmpty())) return null;
        return start;
    }

    private static StructureInfo structureInfo(GenerationHandle handle, BlockPos locate, Start start) {
        var registryId = handle.registries().get(RegistryKeys.STRUCTURE).getId(start.structure());
        // Packs can define an anonymous inline structure. It wins vanilla selection but has no ID to publish.
        if (registryId == null) return null;
        var id = registryId.toString();
        return new StructureInfo(typeOf(id), id, locate.getX(), locate.getZ(), start.position().position().getY(),
            null, null, null, "high", null, null, "resolved");
    }

    private static String typeOf(String id) {
        if (id.startsWith("minecraft:village_")) return "minecraft:village";
        if (id.equals("minecraft:shipwreck_beached")) return "minecraft:shipwreck";
        if (id.startsWith("minecraft:ocean_ruin_")) return "minecraft:ocean_ruin";
        if (id.startsWith("minecraft:ruined_portal")) return "minecraft:ruined_portal";
        return id;
    }

    private static SearchResult result(List<StructureInfo> structures, int radius, long started, boolean timedOut,
            int checked, int skipped, boolean disabled) {
        int found = structures.size();
        var coverage = EventData.of("generator", "builtin", "absence_proven", false, "candidate_radius", radius,
            "candidate_limit", RESULT_LIMIT, "candidates_found", found, "truncated", found > RESULT_LIMIT,
            "truncated_by_budget", timedOut, "elapsed_ms", Math.round((System.nanoTime() - started) / 100_000.0) / 10.0,
            "chunks_checked", checked, "skipped_placements", skipped, "terrain_note", TERRAIN_NOTE);
        if (disabled) {
            var fields = coverage.toJson();
            fields.addProperty("structures_disabled", true);
            coverage = Facts.fromJson(fields);
        }
        return new SearchResult(List.copyOf(structures.subList(0, Math.min(found, RESULT_LIMIT))), coverage);
    }

    private static boolean expired(long deadline) {
        return System.nanoTime() - deadline >= 0;
    }
}
